-- Homepage media slots (S3 / local path references in `path`).
-- Run against the app database after deploy. App also INSERT IGNOREs seed rows on first list.

CREATE TABLE IF NOT EXISTS site_media (
  slot_key VARCHAR(64) PRIMARY KEY,
  label VARCHAR(120) NOT NULL,
  section VARCHAR(64) NOT NULL,
  path VARCHAR(512) NULL,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_site_media_section (section)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

